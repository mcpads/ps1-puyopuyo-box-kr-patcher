/// 전체 입력을 불변 원본에서 한 번 합성하도록 스타일과 추가 cell을 결합한다.
pub(super) const fn join_blocks<const N: usize>(
    styles: &[TextBlockSpec<'static>; 9],
    extra: &[TextBlockSpec<'static>],
) -> [TextBlockSpec<'static>; N] {
    assert!(N == styles.len() + extra.len());
    let mut result = [styles[0]; N];
    let mut i = 0;
    while i < N {
        result[i] = if i < styles.len() {
            styles[i]
        } else {
            extra[i - styles.len()]
        };
        i += 1;
    }
    result
}
